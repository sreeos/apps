function render() {
  const text = $('in').value.toUpperCase(), gap = ' '.repeat(+$('gap').value), w = +$('sc').value, fill = $('ch').value;
  const rows = Array.from({ length: 5 }, () => '');
  for (const ch of text) {
    const gl = FONT[ch] || FONT['?'];
    for (let y = 0; y < 5; y++) {
      rows[y] += [...gl[y]].map((p) => (p === '#' ? (fill === 'same' ? ch : fill) : ' ').repeat(w)).join('') + gap.repeat(w);
    }
  }
  $('out').textContent = rows.map((r) => r.replace(/\s+$/, '')).join('\n');
}
$('in').oninput = $('ch').onchange = $('gap').onchange = $('sc').onchange = render;
$('copy').onclick = async () => {
  try { await sreeos.clipboard.write($('out').textContent); $('msg').textContent = 'Copied'; }
  catch { const s = getSelection(), r = document.createRange(); r.selectNodeContents($('out')); s.removeAllRanges(); s.addRange(r); $('msg').textContent = 'Selected - press Ctrl+C'; }
};
render();
